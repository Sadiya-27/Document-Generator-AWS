"""
Utility functions module.
"""

def add(a, b):
    """
    Adds two numbers.

    Args:
        a (int): First number
        b (int): Second number

    Returns:
        int: Sum
    """
    return a + b

def multiply(a, b):
    """
    Multiplies two numbers.

    Args:
        a (int): First number
        b (int): Second number

    Returns:
        int: Product
    """
    return a * b

